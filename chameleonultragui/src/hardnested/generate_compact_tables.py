#!/usr/bin/env python3
"""Pack the original bitflip tables losslessly; no network or new table oracle."""
import lzma
from pathlib import Path
import re
import struct


def main():
    root = Path(__file__).parent
    source = (root / 'tables.c').read_text()
    threshold = float(re.search(r'^#define IGNORE_BITFLIP_THRESHOLD ([0-9.]+)$',
                                (root.parent / 'hardnested.c').read_text(), re.M)[1])
    pages = [bytes(256)]
    indices = {pages[0]: 0}
    tables = []
    for side, flip, contents in re.findall(
        r'uint8_t bitflip_(\d)_([0-9a-f]+)_states_bin_xz\[\] = \{(.*?)\};', source, re.S
    ):
        raw = lzma.decompress(bytes.fromhex(''.join(re.findall(r'0x([0-9a-f]{2})', contents))))
        assert len(raw) == 4 + (1 << 21)
        count, = struct.unpack_from('<I', raw)
        assert int(side) < 2 and 0 < int(flip, 16) < 1024 and count <= (1 << 24)
        if count / (1 << 24) >= threshold:
            continue
        directory = []
        for offset in range(4, len(raw), 256):
            page = raw[offset:offset + 256]
            if page not in indices:
                indices[page] = len(pages)
                pages.append(page)
            directory.append(indices[page])
        tables.append(struct.pack('<III8192H', int(side), int(flip, 16), count, *directory))
    assert 0 < len(pages) <= 65536 and tables
    packed = struct.pack('<III', 0x31544348, len(pages), len(tables)) + b''.join(pages) + b''.join(tables)
    compressed = lzma.compress(packed, preset=6, check=lzma.CHECK_CRC32)
    lines = ['// Generated by generate_compact_tables.py from tables.c (GPL-3.0-or-later).',
             '// Shared 256-byte pages, little-endian words and page indices.',
             'static const uint8_t compact_bitflip_xz[] = {']
    for offset in range(0, len(compressed), 16):
        lines.append('    ' + ', '.join(f'0x{byte:02x}' for byte in compressed[offset:offset + 16]) + ',')
    lines.extend(['};', f'#define COMPACT_BITFLIP_BYTES {len(packed)}u', ''])
    (root / 'tables_compact.h').write_text('\n'.join(lines))
    print(f'{len(tables)} tables, {len(pages)} unique pages, {len(packed)} decoded bytes, {len(compressed)} compressed bytes')


if __name__ == '__main__':
    main()
